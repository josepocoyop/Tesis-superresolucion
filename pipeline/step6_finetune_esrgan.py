"""
Step 6 — Real-ESRGAN fine-tuning on the CCTV dataset (paired data).

Fine-tunes the pretrained RealESRGAN_x4plus generator on the LR/HR frame
pairs produced by Step 2, fulfilling the thesis objective of training the
model with hyperparameter adjustment (learning rate, batch size, number
of iterations are set in config.py and logged with the run).

After training, the fine-tuned generator is run on all LR frames and the
results are saved to output/sr_finetuned/ for comparison in Step 7.

Requires an NVIDIA GPU with CUDA. With the default 5000 iterations, expect
roughly an hour on an RTX 4070 Ti (2-3 hours on a Colab T4).

Usage:
    python step6_finetune_esrgan.py                 # train + inference
    python step6_finetune_esrgan.py --iters 2000    # shorter training run
    python step6_finetune_esrgan.py --skip-train    # inference only (weights exist)
"""

import sys
import subprocess
import argparse
import shutil
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from config import (
    FRAMES_HR_DIR, FRAMES_LR_DIR, FRAMES_SR_FT_DIR,
    REALESRGAN_DIR, REALESRGAN_REPO_URL,
    ESRGAN_WEIGHTS, ESRGAN_FT_WEIGHTS,
    SCALE_FACTOR, FINETUNE_ITERS, FINETUNE_LR, FINETUNE_BATCH,
)


def install_deps():
    pkgs = ['basicsr', 'realesrgan', 'facexlib', 'gfpgan',
            'torch', 'torchvision', 'opencv-python', 'numpy', 'tqdm', 'pyyaml']
    subprocess.run([sys.executable, '-m', 'pip', 'install', '-q'] + pkgs, check=True)


def patch_basicsr():
    """Fix the known basicsr/torchvision import incompatibility.

    Recent torchvision removed transforms.functional_tensor; basicsr 1.4.2
    still imports rgb_to_grayscale from it. Redirect the import so training
    works with recent torchvision versions.
    """
    import basicsr
    deg = Path(basicsr.__file__).parent / 'data' / 'degradations.py'
    src = deg.read_text(encoding='utf-8')
    bad = 'from torchvision.transforms.functional_tensor import rgb_to_grayscale'
    good = 'from torchvision.transforms.functional import rgb_to_grayscale'
    if bad in src:
        deg.write_text(src.replace(bad, good), encoding='utf-8')
        print('Patched basicsr degradations.py (torchvision compatibility).')


def clone_repo():
    if REALESRGAN_DIR.exists():
        print(f'Real-ESRGAN repo found: {REALESRGAN_DIR}')
        return
    print('Cloning Real-ESRGAN repository...')
    subprocess.run(['git', 'clone', '--depth', '1', REALESRGAN_REPO_URL,
                    str(REALESRGAN_DIR)], check=True)


def write_meta_info() -> Path:
    """Paired meta_info file: '<hr_relpath>, <lr_relpath>' per line."""
    meta = REALESRGAN_DIR / 'meta_info_cctv_pairs.txt'
    hr_frames = sorted(FRAMES_HR_DIR.glob('*.png'))
    lines = []
    for hr in hr_frames:
        lr = FRAMES_LR_DIR / hr.name
        if lr.exists():
            lines.append(f'{hr.name}, {hr.name}')
    meta.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Meta info written: {meta}  ({len(lines)} pairs)')
    return meta


