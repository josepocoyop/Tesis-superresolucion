def run_training(yml: Path):
    print('\nLaunching fine-tuning (this takes a while)...\n')
    subprocess.run(
        [sys.executable, 'realesrgan/train.py', '-opt', str(yml), '--auto_resume'],
        cwd=str(REALESRGAN_DIR), check=True,
    )


def export_weights(iters: int):
    """Copy the last EMA checkpoint to weights/RealESRGAN_x4plus_finetuned.pth."""
    exp_dir = REALESRGAN_DIR / 'experiments' / 'finetune_RealESRGANx4plus_cctv' / 'models'
    candidates = sorted(exp_dir.glob('net_g_*.pth'),
                        key=lambda p: int(p.stem.split('_')[-1]) if p.stem.split('_')[-1].isdigit() else -1)
    if not candidates:
        print(f'ERROR: No checkpoint found in {exp_dir}')
        sys.exit(1)
    last = candidates[-1]
    shutil.copy2(last, ESRGAN_FT_WEIGHTS)
    print(f'Fine-tuned weights exported: {last.name} → {ESRGAN_FT_WEIGHTS}')


def run_inference(tile: int):
    import cv2
    import torch
    from tqdm import tqdm
    from basicsr.archs.rrdbnet_arch import RRDBNet
    from realesrgan import RealESRGANer

    model = RRDBNet(num_in_ch=3, num_out_ch=3, num_feat=64, num_block=23,
                    num_grow_ch=32, scale=SCALE_FACTOR)
    upsampler = RealESRGANer(
        scale=SCALE_FACTOR, model_path=str(ESRGAN_FT_WEIGHTS), model=model,
        tile=tile, tile_pad=10, pre_pad=0, half=torch.cuda.is_available(),
    )

    lr_frames = sorted(FRAMES_LR_DIR.glob('*.png'))
    FRAMES_SR_FT_DIR.mkdir(parents=True, exist_ok=True)
    print(f'\nRunning fine-tuned model on {len(lr_frames)} LR frames...')
    for lr_path in tqdm(lr_frames, unit='frame'):
        img = cv2.imread(str(lr_path), cv2.IMREAD_COLOR)
        if img is None:
            continue
        output, _ = upsampler.enhance(img, outscale=SCALE_FACTOR)
        cv2.imwrite(str(FRAMES_SR_FT_DIR / lr_path.name), output)

    count = len(list(FRAMES_SR_FT_DIR.glob('*.png')))
    print(f'Saved to: {FRAMES_SR_FT_DIR}  ({count} files)')


def main():
    parser = argparse.ArgumentParser(description='Step 6: Fine-tune Real-ESRGAN on CCTV pairs')
    parser.add_argument('--iters', type=int, default=FINETUNE_ITERS,
                        help=f'Total training iterations (default: {FINETUNE_ITERS})')
    parser.add_argument('--skip-train', action='store_true',
                        help='Skip training; run inference with existing fine-tuned weights')
    parser.add_argument('--tile', type=int, default=0,
                        help='Tile size for inference (0=no tiling)')
    args = parser.parse_args()

    install_deps()
    patch_basicsr()
    import torch

    print('=' * 60)
    print('STEP 6 — Real-ESRGAN fine-tuning on CCTV paired data')
    print('=' * 60)
    print(f'  Iterations    : {args.iters}')
    print(f'  Learning rate : {FINETUNE_LR}')
    print(f'  Batch size    : {FINETUNE_BATCH}')
    print()

    if not torch.cuda.is_available() and not args.skip_train:
        print('ERROR: Fine-tuning requires an NVIDIA GPU with CUDA available.')
        sys.exit(1)

    if not args.skip_train:
        if not ESRGAN_WEIGHTS.exists():
            print(f'ERROR: Base weights not found: {ESRGAN_WEIGHTS}')
            print('       Run step3_esrgan_inference.py first (it downloads them).')
            sys.exit(1)
        hr_count = len(list(FRAMES_HR_DIR.glob('*.png')))
        if hr_count == 0:
            print(f'ERROR: No HR frames in {FRAMES_HR_DIR}. Run step2 first.')
            sys.exit(1)
        print(f'Training pairs available: {hr_count}')

        clone_repo()
        meta = write_meta_info()
        yml = write_train_yaml(args.iters, meta)
        run_training(yml)
        export_weights(args.iters)
    elif not ESRGAN_FT_WEIGHTS.exists():
        print(f'ERROR: --skip-train given but {ESRGAN_FT_WEIGHTS} does not exist.')
        sys.exit(1)

    run_inference(args.tile)
    print('\nStep 6 complete. Run step7_compute_metrics.py next.')


if __name__ == '__main__':
    main()
